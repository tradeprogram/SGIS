/** LLM 키가 없거나 호출이 실패했을 때의 폴백. 화면 값만으로 답한다. */
export function localAnswer(message: string, ctx: any): string {
  const d = ctx?.day;
  const head = d
    ? `현재 보고 계신 날짜는 ${d.date}이고, 전국 위험 수준은 "${d.level ?? "—"}" 등급입니다(5년 741일 분포에서 상위 ${
        d.topPct != null ? d.topPct.toFixed(1) : "—"
      }%). 이 날 상위 1% 격자에 사는 인구는 ${
        d.e1 != null ? d.e1.toLocaleString("ko-KR") : "—"
      }명, 상위 5%는 ${d.e5 != null ? d.e5.toLocaleString("ko-KR") : "—"}명입니다.`
    : "아직 날짜가 선택되지 않았습니다.";

  const fire =
    d && d.n > 0
      ? ` 이 날 실제로 기록된 산불은 ${d.n}건, 피해면적 합계 ${d.ha}ha입니다.`
      : d
        ? " 이 날 기록된 산불은 없습니다."
        : "";

  return (
    `${head}${fire}\n\n` +
    `지금은 AI 응답 기능이 연결되어 있지 않아 화면에 표시된 값만 안내해 드립니다. ` +
    `자세한 해석이 필요하시면 환경변수 GEMINI_API_KEY 를 설정해 주십시오.\n\n` +
    `참고로 이 지도의 위험도는 발생확률이 아니라 전국 403,385격자 안에서의 상대 순위입니다. ` +
    `"상위 1%"는 전국에서 가장 위험한 4,034개 격자에 든다는 뜻입니다.`
  );
}

/** 화면 상태에 맞춰 던질 만한 후속 질문을 고른다. */
export function suggestions(ctx: any): string[] {
  const out: string[] = [];
  if (ctx?.day?.n > 0) out.push("이 날 실제 발화를 모델이 잡았나요?");
  else out.push("오늘은 왜 위험 등급이 이렇게 나왔나요?");
  if (ctx?.mode === "detail") out.push("대응 우선지역은 어떻게 정해졌나요?");
  else out.push("대응 우선지역은 왜 안 보이나요?");
  out.push("이 위험도를 확률로 봐도 되나요?");
  out.push("예측이 틀리는 경우는 언제인가요?");
  return out.slice(0, 4);
}
